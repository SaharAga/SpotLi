/**
 * Extracts shelf number (מדף) if present in message body.
 * @param {string} text
 * @returns {string|null}
 */
export function extractShelfNumber(text = '') {
  if (!text || typeof text !== 'string') return null;
  const patterns = [
    /(?:(?:מספר\s+|מס['׳]?\s+)?(?:ב)?מדף(?:\s*(?:מספר|מס['׳]?))?)[\s:#*-]+([א-ת0-9]{1,4}(?:[/-][א-ת0-9]{1,4})?|[א-ת]?\d{1,4}[א-ת]?)(?:[^\S\r\n]|$|[.,;!])/i,
    /(?:\b(?:shelf|bin)\s*(?:number|no|num|#)?)[\s:#*-]+([a-z0-9]{1,4}(?:-[a-z0-9]{1,4})?|[a-z]?\d{1,4}[a-z]?)(?:[^\S\r\n]|$|[.,;!])/i
  ];
  for (const pattern of patterns) {
    const match = pattern.exec(text);
    if (match && match[1]) {
      const shelf = match[1].trim();
      if (shelf && !/^(?:http|https|null|undefined)$/i.test(shelf)) {
        return shelf;
      }
    }
  }
  return null;
}

/**
 * Extracts pickup location or locker info from Hebrew and English SMS/Email text snippets.
 * @param {string} text 
 * @returns {string}
 */
export function extractPickupLocation(text = '') {
  if (!text || typeof text !== 'string') return '';

  const patterns = [
    /(?:נקודת\s*איסוף|בנקודת\s*איסוף|נקודת\s*מסירה|בנקודת\s*מסירה|מרכז\s*מסירה|במרכז\s*מסירה|בלוקר|לוקר|ביחידת\s*(?:ה)?דואר|יחידת\s*(?:ה)?דואר|בסוכנות\s*(?:ה)?דואר|סוכנות\s*(?:ה)?דואר|בסניף\s*מסירה|סניף\s*מסירה|בסניף|סניף|בכתובת|כתובת\s*לאיסוף|בחנות|בבית\s*עסק|נקודת\s*חלוקה|בנקודת\s*חלוקה|איסוף\s*מ|מחכה\s*לך\s*ב|ממתינה\s*לך\s*ב|נמצאת\s*ב)[\s:-]+([^,.\r\n]{2,60})/i,
    /(?:waiting\s+(?:for\s+you\s+)?at\s+(?:the\s+)?(?:pickup\s+point|locker|branch)|at\s+(?:the\s+)?pickup\s+point|at\s+(?:the\s+)?locker|at\s+(?:the\s+)?branch|pickup\s+location|pickup\s+point|locker\s+location|waiting\s+(?:for\s+you\s+)?at)[\s:-]+([^,.\r\n]{2,60})/i
  ];

  for (const pattern of patterns) {
    const match = pattern.exec(text);
    if (match && match[1]) {
      let loc = match[1].trim();
      loc = loc.replace(/^(?:(?:at\s+)?(?:the\s+)?(?:pickup\s+point|pickup\s+location|locker|branch)[\s:-]*)+/i, '');
      loc = loc.replace(/(?:\s*[-–—|/.]?\s*(?:שעות\s*פתיחה|שעות\s*פעילות|קוד\s*איסוף|קוד\s*לאיסוף|קוד|טלפון|טל|בירורים|לינק|כתובת|הוראות|phone|tel|hours|open\s+until|open|pin|code|http|https).*)$/i, '');
      loc = loc.replace(/^['":\-–—\s]+|['":\-–—\s]+$/g, '');
      if (loc && loc.length >= 2 && !/^(?:http|https|www|israelpost|hfd|boxit|chita|buzzr)$/i.test(loc)) {
        return loc;
      }
    }
  }

  return '';
}

/**
 * Extracts opening hours string from raw courier SMS or email text.
 * @param {string} text
 * @returns {string} Extracted hours string or empty
 */
export function extractOpeningHours(text = '') {
  if (!text || typeof text !== 'string') return '';

  const patterns = [
    /\b(24\/7(?:\s*\([^)]+\))?|תמיד\s*פתוח|פתוח\s*24\s*שעות)\b/i,
    /(?:שעות\s*פתיחה|שעות\s*פעילות|שעות\s*מסירה|שעות\s*קבלת\s*קהל|זמני\s*פתיחה)[\s:-]+([^\r\n,;.]+(?:,[^\r\n,;.]+)?)/i,
    /(?:opening\s*hours|business\s*hours|hours\s*of\s*operation)[\s:-]+([^\r\n,;.]+(?:,[^\r\n,;.]+)?)/i,
    /\bhours[\s:-]+([^\r\n,;.]+(?:,[^\r\n,;.]+)?)/i
  ];

  for (const pattern of patterns) {
    const match = pattern.exec(text);
    if (match) {
      const raw = match[1] || match[0];
      let cleaned = raw.trim().slice(0, 200);
      cleaned = cleaned.replace(/(?:\s*[-–—|/.]?\s*(?:טלפון|טל|נייד|phone|tel|קוד|איסוף|כתובת|בירורים|לינק|דואר|http|https).*)$/i, '');
      cleaned = cleaned.replace(/^['":\-–—.\s]+|['":\-–—.\s]+$/g, '');
      if (cleaned && cleaned.length >= 4 && !/^(?:http|https|www)$/i.test(cleaned)) {
        return cleaned;
      }
    }
  }

  return '';
}

/**
 * Extracts a store, courier, or pickup contact phone number from text.
 * Handles Israeli landline formats (02/03/04/08/09-XXXXXXX), mobile (05X-XXXXXXX),
 * VoIP/special (07X-XXXXXXX, 1-700/1-800), and international (+972...).
 * @param {string} text
 * @returns {string}
 */
export function extractPickupPhone(text = '') {
  if (!text || typeof text !== 'string') return '';

  const patterns = [
    /(?:טלפון(?:\s*לבירורים|\s*ליצירת\s*קשר|\s*סניף|\s*חנות)?|טל['׳]|נייד|שליח\s*בטלפון|בירורים(?:\s*במוקד)?|מוקד|phone|tel|call)[\s:-]+(\+?972[- ]?[0-9]{1,2}[- ]?[0-9]{3}[- ]?[0-9]{4}|0[2-9][- ]?[0-9]{7}|05[0-9][- ]?[0-9]{7}|1-[78]00[- ]?[0-9]{3}[- ]?[0-9]{3})\b/i,
    /(?:\+972[- ]?[2-9][- ]?[0-9]{7}|0[23489][- ]?[0-9]{7}|05[0-9][- ]?[0-9]{7}|1-[78]00[- ]?[0-9]{3}[- ]?[0-9]{3})\b/
  ];

  for (const pattern of patterns) {
    const match = pattern.exec(text);
    if (match && match[1]) {
      const phone = match[1].trim().replace(/[^\d+]/g, '');
      if (phone.length >= 7 && phone.length <= 15) {
        return match[1].trim();
      }
    } else if (match && match[0]) {
      const phone = match[0].trim().replace(/[^\d+]/g, '');
      if (phone.length >= 7 && phone.length <= 15) {
        return match[0].trim();
      }
    }
  }

  return '';
}

/**
 * Detects whether a delivery was rerouted / redirected to an alternate pickup point.
 * Extracts the redirect flag, reason, and original location if mentioned.
 * @param {string} text
 * @returns {{ isRedirected: boolean, originalPickupLocation?: string, redirectReason?: string, newPickupLocation?: string }}
 */
export function extractRedirectInfo(text = '') {
  if (!text || typeof text !== 'string') return { isRedirected: false };

  const prefixRedirectMatch = /(?:בשל|עקב)\s*(?:עומס|ביקוש|תפוסה|סגירה|תקלה|אילוץ\s*תפעולי)\s*(?:בלוקר|בסניף|בנקודת\s*איסוף|ב)?\s*([^,.\r\n]+?)\s*,\s*(?:(?:החבילה|חבילתך|המשלוח|משלוח)\s*[A-Za-z0-9_-]*\s*)?(?:הועברה|הופנתה|נותבה|נשלחה)\s*(?:ל|אל)?\s*(?:נקודת\s*איסוף|סניף|לוקר|חנות)?[\s:-]+([^,.\r\n]{2,60})/i.exec(text);
  if (prefixRedirectMatch && prefixRedirectMatch[1] && prefixRedirectMatch[2]) {
    let origLoc = prefixRedirectMatch[1].trim().replace(/^['":\-–—\s()]+|['":\-–—\s()]+$/g, '');
    origLoc = origLoc.replace(/^(?:לוקר|סניף|נקודת\s*איסוף)\s*/i, '');
    let newLoc = prefixRedirectMatch[2].trim().replace(/(?:\s*[-–—|/]?\s*(?:שעות\s*פתיחה|קוד\s*איסוף|קוד|שעות\s*פעילות|טלפון|phone|hours).*)$/i, '').replace(/^['":\-–—\s()]+|['":\-–—\s()]+$/g, '');
    return {
      isRedirected: true,
      newPickupLocation: newLoc,
      originalPickupLocation: origLoc || undefined,
      redirectReason: /(?:עומס|capacity|overflow)/i.test(text) ? 'locker_capacity' : 'operational'
    };
  }

  const redirectPatterns = [
    /(?:עקב|בשל)\s*(?:עומס|ביקוש|תפוסה|סגירה|תקלה|אילוץ\s*תפעולי)[^.\r\n]*?(?:הועברה|הופנתה|נותבה|נשלחה)\s*(?:ל|אל)?\s*(?:נקודת\s*איסוף|סניף|לוקר|חנות)?[\s:-]+([^,.\r\n]{2,60})/i,
    /(?:נקודת\s*(?:ה)?איסוף\s*(?:שונתה|הוחלפה|עודכנה)\s*(?:ל|אל)?[\s:-]+)([^,.\r\n]{2,60})/i,
    /(?:הועברה\s*לנקודת\s*איסוף\s*חלופית[\s:-]+)([^,.\r\n]{2,60})/i,
    /(?:חבילתך\s*הועברה\s*(?:ל|אל)?\s*(?:נקודת\s*איסוף|סניף|לוקר)?[\s:-]+)([^,.\r\n]{2,60})/i,
    /(?:(?:redirected|rerouted|transferred)\s+(?:to\s+(?:pickup\s+(?:point|location)|locker|branch)?|at)[\s:-]+)([^,.\r\n]{2,60})/i,
    /(?:pickup\s+(?:point|location)\s+(?:changed|redirected|updated)\s+to[\s:-]+)([^,.\r\n]{2,60})/i
  ];

  for (const pattern of redirectPatterns) {
    const match = pattern.exec(text);
    if (match && match[1]) {
      let newLoc = match[1].trim();
      newLoc = newLoc.replace(/(?:\s*\(?(?:במקום|במקור|instead\s+of).*\)?)$/i, '');
      newLoc = newLoc.replace(/(?:\s*[-–—|/]?\s*(?:שעות\s*פתיחה|קוד\s*איסוף|שעות\s*פעילות|טלפון|phone|hours).*)$/i, '');
      newLoc = newLoc.replace(/^['":\-–—\s()]+|['":\-–—\s()]+$/g, '');

      let origLoc = '';
      const origMatch = /(?:במקום|במקור|originally|instead\s+of)[\s:-]+([^,.)\r\n]{2,60})/i.exec(text);
      if (origMatch && origMatch[1]) {
        origLoc = origMatch[1].trim().replace(/^['":\-–—\s()]+|['":\-–—\s()]+$/g, '');
      }

      return {
        isRedirected: true,
        newPickupLocation: newLoc,
        originalPickupLocation: origLoc || undefined,
        redirectReason: /(?:עומס|capacity|overflow)/i.test(text) ? 'locker_capacity' : 'operational'
      };
    }
  }

  if (/(?:הועברה\s*לנקודת\s*איסוף\s*חלופית|עקב\s*עומס\s*בלוקר|שונתה\s*נקודת\s*האיסוף|package\s*redirected|was\s*redirected|rerouted\s*to\s*alternate)/i.test(text)) {
    return {
      isRedirected: true,
      redirectReason: /(?:עומס|capacity|overflow)/i.test(text) ? 'locker_capacity' : 'operational'
    };
  }

  return { isRedirected: false };
}

function extractOrderNumberFromText(text = '') {
  if (!text) return undefined;
  const match = text.match(/(?:order\s*(?:id|#|no|number)?|מספר\s*הזמנה|הזמנה\s*(?:מס|מספר|מס׳|מס'))\s*[:：#]?\s*([A-Za-z0-9-]{6,35})\b/i);
  if (!match) return undefined;
  const cand = match[1].trim();
  if (cand.length < 6) return undefined;
  if (/^(?:19|20)\d{6,}$/.test(cand)) return undefined;
  return cand;
}

/**
 * Extracts tracking details and ranked candidates from email with multi-signal evidence scoring.
 * Backwards-compatible with all existing callers while exposing v2.0.0 additive fields.
 *
 * @param {string} subject
 * @param {string} body
 * @param {string} [from]
 * @param {object} [options]
 * @returns {object}
 */
export function extractTrackingDetails(subject = '', body = '', from = '', options = {}) {
  const startTime = Date.now();
  const htmlContent = options.html || (/<script|<html|<div|<a\s+/i.test(body) ? body : '');
  const cleanBody = sanitizeEmailHtml(body);
  const combinedText = `${subject} ${cleanBody} ${from}`.slice(0, 25000);
  const textOrderNumber = extractOrderNumberFromText(combinedText);
  const store = resolveStoreName(from, combinedText);
  const lockerPin = extractLockerPin(combinedText);
  const shelfNumber = extractShelfNumber(combinedText);
  const rawPickupLocation = extractPickupLocation(combinedText);
  const redirectInfo = extractRedirectInfo(combinedText);
  const pickupLocation = redirectInfo.newPickupLocation || rawPickupLocation;
  const pickupHours = extractOpeningHours(combinedText);
  const pickupPhone = extractPickupPhone(combinedText);

  const candidatesMap = new Map();

  // 0. Schema.org / JSON-LD Structured Data Extraction (Authoritative Merchant Data)
  const schemaShipments = extractSchemaOrgData(htmlContent);
  let schemaTitle = '';
  let schemaStore = '';
  let schemaStatus = '';

  for (const shipment of schemaShipments) {
    let tn = shipment.trackingNumber;
    let mappedCarrier = mapCarrierNameToId(shipment.carrier);

    if (shipment.trackingUrl) {
      const urlCandidate = extractTrackingFromUrl(shipment.trackingUrl);
      if (urlCandidate) {
        if (!tn) tn = urlCandidate.trackingNumber;
        if (!mappedCarrier || mappedCarrier === 'other') mappedCarrier = urlCandidate.carrier;
      }
    }

    if (tn && !isFalsePositive(tn, combinedText)) {
      const cleanVal = tn.trim().toUpperCase();
      let checksum = 'not-applicable';

      if (!mappedCarrier || mappedCarrier === 'other') {
        for (const rule of COMPILED_RULES) {
          if (rule.re.test(cleanVal)) {
            mappedCarrier = rule.carrierId;
            checksum = evaluateChecksum(cleanVal, rule.checksum);
            break;
          }
        }
      } else {
        const rule = COMPILED_RULES.find((r) => r.carrierId === mappedCarrier && r.re.test(cleanVal));
        if (rule) {
          checksum = evaluateChecksum(cleanVal, rule.checksum);
        }
      }

      if (shipment.title && !schemaTitle) schemaTitle = shipment.title;
      if (shipment.store && !schemaStore) schemaStore = shipment.store;
      if (shipment.status && !schemaStatus) schemaStatus = shipment.status;

      if (!candidatesMap.has(cleanVal)) {
        candidatesMap.set(cleanVal, {
          id: `cand_${candidatesMap.size + 1}`,
          value: cleanVal,
          carrierCandidates: [mappedCarrier || 'other'],
          formatMatch: true,
          checksum,
          urlDomainMatch: Boolean(shipment.trackingUrl),
          schemaOrgMatch: true,
          labelProximity: 1.0,
          falsePositiveFlags: [],
          sourceSpan: { start: 0, end: 0 },
          score: 0.98
        });
      }
    }
  }

  // 1. Courier URL Link Extraction (Highest Priority)
  for (const { carrier, pattern } of CARRIER_URL_PATTERNS) {
    const gPattern = new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`);
    let urlMatch;
    while ((urlMatch = gPattern.exec(combinedText)) !== null) {
      const candidateVal = urlMatch[1] || urlMatch[2] || urlMatch[3];
      if (candidateVal && !isFalsePositive(candidateVal, combinedText)) {
        const cleanVal = candidateVal.trim().toUpperCase();
        if (!candidatesMap.has(cleanVal)) {
          candidatesMap.set(cleanVal, {
            id: `cand_${candidatesMap.size + 1}`,
            value: cleanVal,
            carrierCandidates: [carrier],
            formatMatch: true,
            checksum: 'not-applicable',
            urlDomainMatch: true,
            labelProximity: 1.0,
            falsePositiveFlags: [],
            sourceSpan: { start: urlMatch.index || 0, end: (urlMatch.index || 0) + urlMatch[0].length },
            score: 0.95
          });
        }
      }
      if (urlMatch[0].length === 0) {
        gPattern.lastIndex += 1;
      }
    }
  }

  // 2. Scan Labeled Patterns
  const labeledRegex = /(?:tracking\s*(?:number|id|code|no|#)?|מספר\s*מעקב|מס['׳`״’‘]?\s*מעקב|קוד\s*מעקב|דבר\s*דואר(?:\s*שמספרו)?|חבילתך\s*במספר|חבילה\s*מספר|מספר\s*משלוח|waybill|awb|consign(?:ment)?|ברקוד(?:\s*משלוח)?)[\s:=#-]+([A-Za-z0-9_-]{6,35})/gi;
  let labeledMatch;

  while ((labeledMatch = labeledRegex.exec(combinedText)) !== null) {
    const rawVal = labeledMatch[1];
    const cleanVal = rawVal.trim().toUpperCase();
    if (isFalsePositive(cleanVal, combinedText)) continue;

    let matchedCarrier = 'other';
    let checksum = 'not-applicable';

    for (const rule of COMPILED_RULES) {
      if (rule.re.test(cleanVal)) {
        matchedCarrier = rule.carrierId;
        checksum = evaluateChecksum(cleanVal, rule.checksum);
        break;
      }
    }

    const start = labeledMatch.index + labeledMatch[0].indexOf(rawVal);
    const end = start + rawVal.length;

    // Check local proximity window for carrier hints
    const windowStart = Math.max(0, start - 150);
    const windowEnd = Math.min(combinedText.length, end + 150);
    const localContext = combinedText.slice(windowStart, windowEnd).toLowerCase();

    let formatMatch = matchedCarrier !== 'other';

    if (matchedCarrier === 'other') {
      const candidateRule = COMPILED_RULES.find(
        (r) => r.re.test(cleanVal) && localContext.includes(r.carrierId.toLowerCase())
      );
      if (candidateRule) {
        matchedCarrier = candidateRule.carrierId;
        checksum = evaluateChecksum(cleanVal, candidateRule.checksum);
        formatMatch = true;
      } else if (localContext.includes('amazon') || /^TBA\d+/i.test(cleanVal)) {
        matchedCarrier = 'amazon';
        formatMatch = true;
      } else if (/^\d{6,10}$/.test(cleanVal)) {
        if (/chita|cheetah|צ['׳`״]?יטה/i.test(localContext)) { matchedCarrier = 'chita'; formatMatch = true; }
        else if (/hfd|epost|אי-?פוסט/i.test(localContext)) { matchedCarrier = 'hfd'; formatMatch = true; }
        else if (/boxit|בוקסיט/i.test(localContext)) { matchedCarrier = 'boxit'; formatMatch = true; }
        else if (/buzzr|באזר/i.test(localContext)) { matchedCarrier = 'buzzr'; formatMatch = true; }
        else if (/tapuz|תפוז/i.test(localContext)) { matchedCarrier = 'tapuz'; formatMatch = true; }
        else if (/israel\s*post|דואר\s*ישראל/i.test(localContext)) { matchedCarrier = 'israel-post'; formatMatch = true; }
      }
    }

    let score = 0.70;
    if (formatMatch) score += 0.15;
    if (checksum === 'pass') score += 0.15;
    if (checksum === 'fail') score -= 0.10; // modest penalty for placeholder test fixtures
    if (isPromotionalContext(combinedText) && !formatMatch) score -= 0.25;

    if (!candidatesMap.has(cleanVal)) {
      candidatesMap.set(cleanVal, {
        id: `cand_${candidatesMap.size + 1}`,
        value: cleanVal,
        carrierCandidates: [matchedCarrier],
        formatMatch,
        checksum,
        urlDomainMatch: false,
        labelProximity: 1.0,
        falsePositiveFlags: [],
        sourceSpan: { start, end },
        score: Math.min(1.0, Math.max(0.0, score))
      });
    }
  }

  // 3. Scan Tokens against Carrier Rules
  const tokenRegex = /\b([A-Za-z0-9]{6,35})\b/g;
  let tokenMatch;

  while ((tokenMatch = tokenRegex.exec(combinedText)) !== null) {
    const rawVal = tokenMatch[1];
    const cleanVal = rawVal.trim().toUpperCase();
    if (candidatesMap.has(cleanVal) || isFalsePositive(cleanVal, combinedText)) continue;

    for (const rule of COMPILED_RULES) {
      if (rule.re.test(cleanVal)) {
        let checksum = 'not-applicable';
        checksum = evaluateChecksum(cleanVal, rule.checksum);

        // Check proximity if rule is generic digits (e.g. 10 digits for DHL or 12 for FedEx)
        let proximityBoost = 0;
        if (/^\d{10,12}$/.test(cleanVal)) {
          const windowStart = Math.max(0, tokenMatch.index - 120);
          const windowEnd = Math.min(combinedText.length, tokenMatch.index + rawVal.length + 120);
          const localContext = combinedText.slice(windowStart, windowEnd).toLowerCase();
          if (localContext.includes(rule.carrierId.toLowerCase())) {
            proximityBoost = 0.25;
          } else {
            continue; // Skip ambiguous bare digits without carrier keyword nearby
          }
        }

        let score = rule.confidence === 'high' ? 0.70 : 0.45;
        score += proximityBoost;
        if (checksum === 'pass') score += 0.20;
        if (checksum === 'fail') score -= 0.10;

        candidatesMap.set(cleanVal, {
          id: `cand_${candidatesMap.size + 1}`,
          value: cleanVal,
          carrierCandidates: [rule.carrierId],
          formatMatch: true,
          checksum,
          urlDomainMatch: false,
          labelProximity: proximityBoost > 0 ? 0.8 : 0.0,
          falsePositiveFlags: [],
          sourceSpan: { start: tokenMatch.index, end: tokenMatch.index + rawVal.length },
          score: Math.min(1.0, Math.max(0.0, score))
        });
        break;
      }
    }
  }

  const candidates = Array.from(candidatesMap.values()).sort((a, b) => b.score - a.score);
  const selectedCandidate = candidates.length > 0 ? candidates[0] : null;

  let trackingNumber = null;
  let carrier = 'other';
  let status = 'none';
  let confidence = 'none';

  if (selectedCandidate && selectedCandidate.score >= 0.40) {
    trackingNumber = selectedCandidate.value;
    carrier = selectedCandidate.carrierCandidates[0] || 'other';

    if (selectedCandidate.score >= 0.80 && selectedCandidate.checksum !== 'fail') {
      status = 'verified';
      confidence = 'high';
    } else if (selectedCandidate.score >= 0.60) {
      status = 'probable';
      confidence = 'medium';
    } else {
      status = 'uncertain';
      confidence = 'low';
    }
  }

  const effectiveStore = store || schemaStore;
  // Order of preference: what the email's structured data says it is, then
  // what its own contents list says, then whatever can be salvaged from the
  // subject line. The subject is last because it usually names the order, not
  // the thing — "Shipping update for order 469417".
  const itemName = extractShippedItemName(cleanBody);
  const title = schemaTitle
    || (itemName ? (effectiveStore ? `${effectiveStore} - ${itemName}` : itemName) : '')
    || generateCleanTitle(subject, effectiveStore, carrier);
  const latencyMs = Date.now() - startTime;

  const allPackages = [];
  const verifiedCandidates = candidates.filter((c) => (c.score >= 0.80 && c.checksum !== 'fail') || c.schemaOrgMatch);
  const targetCandidates = verifiedCandidates.length > 0
    ? verifiedCandidates
    : (candidates.length > 0 && candidates[0].score >= 0.60 ? [candidates[0]] : []);

  const orderedCandidates = targetCandidates.length > 1
    ? [...targetCandidates].sort((a, b) => (a.sourceSpan?.start ?? 0) - (b.sourceSpan?.start ?? 0))
    : targetCandidates;

  const seenTracking = new Set();
  for (let idx = 0; idx < orderedCandidates.length; idx += 1) {
    const cand = orderedCandidates[idx];
    if (seenTracking.has(cand.value)) continue;
    seenTracking.add(cand.value);

    const tn = cand.value;
    const candCarrier = cand.carrierCandidates[0] || 'other';
    const schemaShipment = schemaShipments.find((s) => s.trackingNumber?.toUpperCase() === tn);

    let candTitle = schemaShipment?.title;
    if (!candTitle) {
      if (targetCandidates.length > 1 && effectiveStore) {
        candTitle = `${effectiveStore} - Shipment #${idx + 1} (${tn.slice(-4)})`;
      } else {
        candTitle = title;
      }
    }

    allPackages.push({
      trackingNumber: tn,
      carrier: candCarrier,
      title: candTitle,
      store: schemaShipment?.store || effectiveStore,
      orderNumber: schemaShipment?.orderNumber || schemaShipments[0]?.orderNumber || textOrderNumber || undefined,
      deliveryStatus: schemaShipment?.status || schemaStatus || undefined,
      pickupLocation: pickupLocation || '',
      pickupHours: pickupHours || undefined,
      pickupPhone: pickupPhone || undefined,
      lockerPin,
      shelfNumber,
      isRedirected: redirectInfo.isRedirected || undefined,
      originalPickupLocation: redirectInfo.originalPickupLocation || undefined,
      redirectReason: redirectInfo.redirectReason || undefined,
      origin: '',
      notes: '',
      status: (cand.score >= 0.80 && cand.checksum !== 'fail') || cand.schemaOrgMatch ? 'verified' : 'probable',
      confidence: (cand.score >= 0.80 && cand.checksum !== 'fail') || cand.schemaOrgMatch ? 'high' : 'medium',
      candidate: cand
    });
  }

  return {
    trackingNumber,
    carrier,
    title,
    store: effectiveStore,
    orderNumber: schemaShipments[0]?.orderNumber || textOrderNumber || undefined,
    deliveryStatus: schemaStatus || undefined,
    pickupLocation: pickupLocation || '',
    pickupHours: pickupHours || undefined,
    pickupPhone: pickupPhone || undefined,
    isRedirected: redirectInfo.isRedirected || undefined,
    originalPickupLocation: redirectInfo.originalPickupLocation || undefined,
    redirectReason: redirectInfo.redirectReason || undefined,
    origin: '',
    notes: '',
    lockerPin,
    shelfNumber,
    status,
    confidence: trackingNumber ? confidence : 'none',
    candidates,
    allPackages,
    selectedCandidate,
    evidenceSummary: selectedCandidate ? [`Selected ${selectedCandidate.value} for ${carrier} (score: ${selectedCandidate.score})`] : [],
    executionPath: selectedCandidate ? 'deterministic_fast_path' : 'safe_abstention',
    latencyMs
  };
}

/**
 * Extracts all verified package tracking details from a message, disaggregating multi-parcel shipments.
 * If multiple parcels are found (e.g. Amazon or AliExpress orders with 2+ tracking numbers), returns an array of all parcels.
 * If no verified tracking numbers are found, returns order status fallback if available, or an empty array.
 *
 * @param {string} subject
 * @param {string} body
 * @param {string} [from]
 * @param {object} [options]
 * @returns {Array<object>}
 */
export function extractAllTrackingDetails(subject = '', body = '', from = '', options = {}) {
  const primary = extractTrackingDetails(subject, body, from, options);
  if (primary.allPackages && primary.allPackages.length > 0) {
    return primary.allPackages;
  }

  const orderStatus = extractOrderStatusDetails(subject, body, from);
  if (orderStatus) {
    return [{
      trackingNumber: '',
      carrier: 'other',
      title: orderStatus.title,
      store: orderStatus.store,
      deliveryStatus: orderStatus.status,
      status: 'none',
      confidence: 'sender_reported',
      isOrderStatusOnly: true
    }];
  }

  return [];
}
