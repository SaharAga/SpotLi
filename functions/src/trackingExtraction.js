const REDIRECT_PARAM_NAMES = new Set([
  'url', 'target', 'dest', 'destination', 'redirect', 'redirect_url',
  'link', 'r', 'u', 'to', 'next', 'forward', 'target_url', 'click_url',
  'orig_url', 'uri', 'goto'
]);

/**
 * Attempts to decode a URL component and returns a clean http(s) URL if valid.
 * Handles single and double percent-encoded URLs.
 * @param {string} val
 * @returns {string|null}
 */
function tryDecodeUrl(val) {
  if (!val || typeof val !== 'string') return null;
  let decoded = val.trim();
  try {
    if (/%[0-9A-Fa-f]{2}/.test(decoded)) {
      decoded = decodeURIComponent(decoded);
      if (/%[0-9A-Fa-f]{2}/.test(decoded)) {
        decoded = decodeURIComponent(decoded);
      }
    }
  } catch {}

  if (/^https?:\/\/[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}/i.test(decoded)) {
    return decoded;
  }
  return null;
}

/**
 * Unwraps nested or redirect URLs generated by email service providers (SendGrid, Klaviyo, AliExpress, Shein, Amazon).
 * @param {string} url
 * @param {number} [maxDepth=3]
 * @returns {string|null} Unwrapped target URL, or null if no redirect parameter found.
 */
export function unwrapRedirectUrl(url, maxDepth = 3) {
  if (!url || typeof url !== 'string') return null;

  let currentUrl = url.trim();
  let unwrapped = null;

  for (let depth = 0; depth < maxDepth; depth++) {
    try {
      const fullUrl = currentUrl.startsWith('http') ? currentUrl : `https://${currentUrl}`;
      const parsed = new URL(fullUrl);

      let extracted = null;

      // 1. Check known redirect parameter keys
      for (const [key, val] of parsed.searchParams.entries()) {
        const lowerKey = key.toLowerCase();
        if (REDIRECT_PARAM_NAMES.has(lowerKey)) {
          const candidate = tryDecodeUrl(val);
          if (candidate) {
            extracted = candidate;
            break;
          }
        }
      }

      // 2. Fallback: inspect parameter values for embedded http/https
      if (!extracted) {
        for (const [_, val] of parsed.searchParams.entries()) {
          if (/https?%3A|https?:\/\//i.test(val)) {
            const candidate = tryDecodeUrl(val);
            if (candidate) {
              extracted = candidate;
              break;
            }
          }
        }
      }

      if (extracted && extracted !== currentUrl) {
        unwrapped = extracted;
        currentUrl = extracted;
      } else {
        break;
      }
    } catch {
      break;
    }
  }

  return unwrapped;
}

/**
 * Normalizes raw carrier names from Schema.org or courier metadata to Deliveree carrier IDs.
 * @param {string} carrierName
 * @returns {string|null}
 */
export function mapCarrierNameToId(carrierName = '') {
  if (!carrierName || typeof carrierName !== 'string') return null;
  const clean = carrierName.trim().toLowerCase();

  if (/ups|united parcel/i.test(clean)) return 'ups';
  if (/fedex|federal express/i.test(clean)) return 'fedex';
  if (/dhl/i.test(clean)) return 'dhl';
  if (/usps|postal service|united states postal/i.test(clean)) return 'usps';
  if (/israel\s*post|דואר\s*ישראל|postil/i.test(clean)) return 'israel-post';
  if (/cainiao|aliexpress/i.test(clean)) return 'cainiao';
  if (/chita|ציטה|צ'יטה/i.test(clean)) return 'chita';
  if (/hfd|epost|אי-?פוסט/i.test(clean)) return 'hfd';
  if (/boxit|בוקסיט/i.test(clean)) return 'boxit';
  if (/buzzr|באזר/i.test(clean)) return 'buzzr';
  if (/tapuz|תפוז/i.test(clean)) return 'tapuz';
  if (/bar[- ]?distribution|בר\s*הפצה|barexpress/i.test(clean)) return 'bar-distribution';
  if (/lionwheel|ליאון\s*וויל/i.test(clean)) return 'lionwheel';
  if (/yunexpress|yuntrack/i.test(clean)) return 'yunexpress';
  if (/yanwen/i.test(clean)) return 'yanwen';
  if (/royal\s*mail/i.test(clean)) return 'royal-mail';
  if (/aramex/i.test(clean)) return 'aramex';

  return null;
}

/**
 * Recursively traverses parsed JSON-LD objects looking for Schema.org ParcelDelivery,
 * Order, and DeliveryEvent shipments.
 * @param {any} obj
 * @param {Array<object>} results
 * @returns {Array<object>}
 */
function findSchemaOrgShipments(obj, results = []) {
  if (!obj || typeof obj !== 'object') return results;

  if (Array.isArray(obj)) {
    for (const item of obj) {
      findSchemaOrgShipments(item, results);
    }
    return results;
  }

  if (obj['@graph'] && Array.isArray(obj['@graph'])) {
    findSchemaOrgShipments(obj['@graph'], results);
  }

  const type = String(obj['@type'] || '');
  const hasTracking = Boolean(obj.trackingNumber || obj.trackingUrl);

  if (/ParcelDelivery|DeliveryEvent/i.test(type) || hasTracking) {
    const trackingNumber = typeof obj.trackingNumber === 'string'
      ? obj.trackingNumber.trim()
      : (typeof obj.trackingNumber === 'number' ? String(obj.trackingNumber) : '');

    const trackingUrl = typeof obj.trackingUrl === 'string' ? obj.trackingUrl.trim() : '';

    let carrierName = '';
    if (typeof obj.carrier === 'string') {
      carrierName = obj.carrier;
    } else if (obj.carrier && typeof obj.carrier.name === 'string') {
      carrierName = obj.carrier.name;
    } else if (typeof obj.hasDeliveryMethod === 'string') {
      carrierName = obj.hasDeliveryMethod;
    }

    let title = '';
    if (typeof obj.itemShipped === 'string') {
      title = obj.itemShipped;
    } else if (obj.itemShipped && typeof obj.itemShipped.name === 'string') {
      title = obj.itemShipped.name;
    } else if (Array.isArray(obj.itemShipped) && obj.itemShipped[0]?.name) {
      title = obj.itemShipped[0].name;
    }

    let store = '';
    let orderNumber = '';
    if (obj.partOfOrder) {
      orderNumber = obj.partOfOrder.orderNumber || '';
      const merchant = obj.partOfOrder.merchant || obj.partOfOrder.seller;
      if (typeof merchant === 'string') store = merchant;
      else if (merchant?.name) store = merchant.name;
    }

    let status = '';
    const rawStatus = String(obj.deliveryStatus || '');
    if (/Delivered/i.test(rawStatus)) status = 'delivered';
    else if (/InTransit|Dispatched/i.test(rawStatus)) status = 'in_transit';
    else if (/Pickup/i.test(rawStatus)) status = 'ready_for_pickup';

    if (trackingNumber || trackingUrl) {
      results.push({
        trackingNumber,
        trackingUrl,
        carrier: carrierName,
        title,
        store,
        orderNumber,
        status,
        expectedArrivalUntil: obj.expectedArrivalUntil || obj.expectedArrivalFrom || ''
      });
    }
  }

  if (/Order/i.test(type)) {
    const orderNumber = obj.orderNumber || '';
    const merchant = obj.merchant || obj.seller;
    const store = typeof merchant === 'string' ? merchant : (merchant?.name || '');

    if (obj.orderDelivery) {
      const deliveries = Array.isArray(obj.orderDelivery) ? obj.orderDelivery : [obj.orderDelivery];
      for (const del of deliveries) {
        if (del && typeof del === 'object') {
          if (!del.partOfOrder) {
            del.partOfOrder = { orderNumber, merchant: store };
          }
          findSchemaOrgShipments(del, results);
        }
      }
    }
  }

  return results;
}

/**
 * Extracts Schema.org structured data (JSON-LD) from email HTML.
 * @param {string} content Raw HTML or JSON-LD payload
 * @returns {Array<{ trackingNumber: string, trackingUrl: string, carrier: string, title: string, store: string, orderNumber: string, status: string, expectedArrivalUntil: string }>}
 */
export function extractSchemaOrgData(content) {
  if (!content || typeof content !== 'string') return [];

  const results = [];
  const trimmed = content.trim();

  // If payload is already a raw JSON string
  if (trimmed.startsWith('{') || trimmed.startsWith('[')) {
    try {
      const parsed = JSON.parse(trimmed);
      findSchemaOrgShipments(parsed, results);
      if (results.length > 0) return results;
    } catch {}
  }

  // Extract from <script type="application/ld+json"> tags
  const scriptRegex = /<script[^>]*type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi;
  let match;

  while ((match = scriptRegex.exec(content)) !== null) {
    const rawJson = match[1]?.trim();
    if (!rawJson) continue;

    try {
      const parsed = JSON.parse(rawJson);
      findSchemaOrgShipments(parsed, results);
    } catch {
      // Ignore malformed JSON in script tags
    }
  }

  return results;
}

