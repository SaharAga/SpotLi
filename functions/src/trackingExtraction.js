/**
 * Extracts tracking number and carrier from a single URL, unwrapping redirects if needed.
 * @param {string} url
 * @returns {{ trackingNumber: string, carrier: string } | null}
 */
export function extractTrackingFromUrl(url) {
  if (!url || typeof url !== 'string') return null;
  const unwrapped = unwrapRedirectUrl(url) || url;

  for (const { carrier, pattern } of CARRIER_URL_PATTERNS) {
    const match = unwrapped.match(pattern);
    const candidateVal = match ? (match[1] || match[2] || match[3]) : null;
    if (candidateVal && !isFalsePositive(candidateVal, unwrapped)) {
      return {
        trackingNumber: candidateVal.trim().toUpperCase(),
        carrier
      };
    }
  }

  try {
    const fullUrl = unwrapped.startsWith('http') ? unwrapped : `https://${unwrapped}`;
    const parsed = new URL(fullUrl);
    const GENERIC_PARAMS = [
      'track', 'tracking', 'num', 'code', 't', 'id', 'barcode', 'item', 'awb', 'b',
      'itemcode', 'mailNoList', 'mailNo', 'trknbr', 'tLabels', 'pNumbers', 'ShipmentNumber', 'tracknum'
    ];
    for (const p of GENERIC_PARAMS) {
      const val = parsed.searchParams.get(p);
      if (val && val.trim().length >= 6 && val.trim().length <= 35 && !isFalsePositive(val, unwrapped)) {
        return {
          trackingNumber: val.trim().toUpperCase(),
          carrier: 'other'
        };
      }
    }
  } catch {}

  return null;
}

/**
 * Strips HTML tags while preserving and extracting embedded hyperlinks and unwrapping redirect URLs.
 * Appends extracted URLs and anchor text so tracking links in buttons/banners are never lost.
 * @param {string} html
 * @returns {string}
 */
export function sanitizeEmailHtml(html) {
  if (typeof html !== 'string') return '';

  // 1. Extract all href links and unwrap ESP redirects
  const linkRegex = /<a\s+(?:[^>]*?\s+)?href=["']([^"']+)["'][^>]*>([\s\S]*?)<\/a>/gi;
  const extractedLinks = [];
  let linkMatch;
  while ((linkMatch = linkRegex.exec(html)) !== null) {
    const href = linkMatch[1];
    const anchorText = linkMatch[2]?.replace(/<[^>]+>/g, '').trim();
    if (href && !href.startsWith('mailto:') && !href.startsWith('javascript:')) {
      const unwrapped = unwrapRedirectUrl(href);
      if (unwrapped) {
        extractedLinks.push(` ${anchorText || ''} ${unwrapped} `);
      }
      extractedLinks.push(` ${anchorText || ''} ${href} `);
    }
  }

  // 2. Remove script and style tags
  let clean = html
    .replace(/<style[^>]*>[\s\S]*?<\/style>/gi, '')
    .replace(/<script[^>]*>[\s\S]*?<\/script>/gi, '');

  // 3. Strip all HTML tags
  clean = clean.replace(/<[^>]+>/g, ' ');

  // 4. Decode common HTML entities
  clean = clean
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/&zwnj;/gi, '')
    .replace(/&zwj;/gi, '')
    .replace(/\s+/g, ' ')
    .trim();

  // 5. Append extracted links at the end so courier URLs are reachable
  if (extractedLinks.length > 0) {
    clean += ' ' + extractedLinks.join(' ');
  }

  return clean;
}

